const dictionaries: Record<Locale, Record<MessageKey, string>> = {
  'zh-CN': zhCN,
  'zh-TW': zhTW,
  en,
}

export const LOCALES: { id: Locale; label: string }[] = [
  { id: 'zh-CN', label: '简体中文' },
  { id: 'zh-TW', label: '繁體中文' },
  { id: 'en', label: 'English' },
]

const STORAGE_KEY = 'pinboard-locale'

function isLocale(value: string | null | undefined): value is Locale {
  return value === 'zh-CN' || value === 'zh-TW' || value === 'en'
}

function detectLocale(): Locale {
  try {
    const stored = localStorage.getItem(STORAGE_KEY)
    if (isLocale(stored)) return stored
  } catch {
    // storage may be unavailable
  }
  if (typeof navigator === 'undefined') return 'zh-CN'
  const languages = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language]
  for (const raw of languages) {
    const lang = (raw || '').toLowerCase()
    if (/^zh-(tw|hk|mo)/.test(lang) || lang.includes('hant')) return 'zh-TW'
    if (lang.startsWith('zh')) return 'zh-CN'
    if (lang.startsWith('en')) return 'en'
  }
  return 'en'
}

let currentLocale: Locale = detectLocale()
const listeners = new Set<(locale: Locale) => void>()

export function getLocale(): Locale {
  return currentLocale
}

export function t(key: MessageKey, params?: Record<string, string | number>): string {
  const template = dictionaries[currentLocale][key] ?? dictionaries['zh-CN'][key] ?? key
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    params[name] !== undefined ? String(params[name]) : `{${name}}`,
  )
}

export function setLocale(locale: Locale): void {
  if (locale === currentLocale) return
  currentLocale = locale
  try {
    localStorage.setItem(STORAGE_KEY, locale)
  } catch {
    // ignore
  }
  applyStaticTranslations()
  for (const listener of listeners) listener(locale)
}

export function onLocaleChange(listener: (locale: Locale) => void): () => void {
  listeners.add(listener)
  return () => listeners.delete(listener)
}

export function applyStaticTranslations(root?: ParentNode): void {
  if (typeof document === 'undefined') return
  const scope = root ?? document
  document.documentElement.lang = currentLocale
  scope.querySelectorAll<HTMLElement>('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n as MessageKey | undefined
    if (key) element.textContent = t(key)
  })
  scope.querySelectorAll<HTMLElement>('[data-i18n-html]').forEach((element) => {
    const key = element.dataset.i18nHtml as MessageKey | undefined
    if (key) element.innerHTML = t(key)
  })
  scope.querySelectorAll<HTMLElement>('[data-i18n-title]').forEach((element) => {
    const key = element.dataset.i18nTitle as MessageKey | undefined
    if (key) element.title = t(key)
  })
  scope.querySelectorAll<HTMLElement>('[data-i18n-aria]').forEach((element) => {
    const key = element.dataset.i18nAria as MessageKey | undefined
    if (key) element.setAttribute('aria-label', t(key))
  })
  scope.querySelectorAll<HTMLInputElement>('[data-i18n-placeholder]').forEach((element) => {
    const key = element.dataset.i18nPlaceholder as MessageKey | undefined
    if (key) element.placeholder = t(key)
  })
  scope.querySelectorAll<HTMLButtonElement>('[data-lang]').forEach((button) => {
    const active = button.dataset.lang === currentLocale
    button.classList.toggle('active', active)
    button.setAttribute('aria-pressed', String(active))
  })
  document.title = t('app.fullName')
}

export function initI18n(): void {
  applyStaticTranslations()
}

