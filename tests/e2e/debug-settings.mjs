import { chromium } from 'playwright-core'
import { randomBytes } from 'node:crypto'
const CHROME = 'C:/Program Files/Google/Chrome/Application/chrome.exe'
const room = 'dbgs-' + randomBytes(12).toString('base64url')
const browser = await chromium.launch({ executablePath: CHROME, headless: true })
const ctx = await browser.newContext({ viewport: { width: 1280, height: 860 }, locale: 'zh-CN' })
const page = await ctx.newPage()
page.on('pageerror', e => console.log('ERR', e.message))
page.on('console', m => { if (m.type() === 'error') console.log('CONSOLE', m.text()) })
await page.goto(`http://127.0.0.1:5173/r/${room}`, { waitUntil: 'domcontentloaded' })
await page.waitForFunction(() => window.__pinboard)
await page.fill('#nameInput', 'Debug')
await page.click('#nameForm button[type=submit]')
await page.waitForSelector('#nameModal', { state: 'hidden' })
await page.waitForTimeout(900)
const center = await page.evaluate(() => {
  const a = window.__pinboard
  const n = a.board.item('seed-welcome')
  const r = document.getElementById('board').getBoundingClientRect()
  return { x: (n.x + n.w/2 - a.camera.x) * a.camera.scale + r.left, y: (n.y + n.h/2 - a.camera.y) * a.camera.scale + r.top }
})
const state = () => page.evaluate(() => ({ flag: window.__pinboard.doubleClickEditsNote, stored: localStorage.getItem('pinboard-dbl-edit'), settings: !document.getElementById('settingsModal').hidden, editor: getComputedStyle(document.getElementById('editor')).display, selHidden: document.getElementById('selectionBar').hidden }))
console.log('before', await state())
await page.mouse.dblclick(center.x, center.y)
await page.waitForTimeout(150)
console.log('dbl before enabled', await state(), 'editorVisible', await page.locator('#editor').isVisible())
await page.click('#btnMenu')
await page.click('[data-menu-action="settings"]')
await page.waitForSelector('#settingsModal:not([hidden])')
console.log('settings open checked', await page.locator('#optDoubleClick').isChecked())
await page.locator('#optDoubleClick').check({ force: true })
console.log('after check', await state(), await page.locator('#optDoubleClick').isChecked())
await page.click('#btnCloseSettings')
await page.waitForSelector('#settingsModal', { state: 'hidden' })
console.log('after close', await state())
await page.mouse.dblclick(center.x, center.y)
await page.waitForTimeout(300)
console.log('dbl after enabled', await state(), 'editorVisible', await page.locator('#editor').isVisible())
await page.screenshot({ path: 'tests/e2e/screenshots/debug-settings.png' })
await browser.close()
