import { chromium } from 'playwright-core'
import { randomBytes } from 'node:crypto'
import assert from 'node:assert/strict'
const CHROME = process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe'
const BASE = process.env.BASE_URL || 'http://127.0.0.1:3001'
const room = 'prod-' + randomBytes(12).toString('base64url')
const browser = await chromium.launch({ executablePath: CHROME, headless: true })
const ctxA = await browser.newContext({ viewport: { width: 1280, height: 860 }, locale: 'en-US' })
const pageA = await ctxA.newPage()
const errors = []
pageA.on('pageerror', e => errors.push(e.message))
pageA.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
await pageA.goto(`${BASE}/r/${room}`, { waitUntil: 'domcontentloaded' })
await pageA.waitForSelector('#nameModal', { state: 'hidden' })
assert.equal(await pageA.locator('#nameModal').isVisible(), false)
await pageA.waitForFunction(() => document.getElementById('connState').innerText.includes('Synced'), null, { timeout: 15000 })
await pageA.waitForTimeout(700)
const initialCount = await pageA.locator('#pinCount').innerText()
assert.equal(initialCount, '1')
await pageA.click('[data-tool="note"]')
const box = await pageA.locator('#board').boundingBox()
await pageA.mouse.click(box.x + box.width * 0.55, box.y + box.height * 0.6)
await pageA.waitForSelector('#editor', { state: 'visible' })
await pageA.fill('#editor', 'Production build works')
await pageA.press('#editor', 'Escape')
await pageA.waitForSelector('#selectionBar:not([hidden])')
await pageA.click('#selectionBar [data-sel-action="pin"]')
await pageA.waitForTimeout(400)
assert.equal(await pageA.locator('#pinCount').innerText(), '2')
await pageA.screenshot({ path: 'tests/e2e/screenshots/60-production.png' })
await pageA.reload({ waitUntil: 'domcontentloaded' })
await pageA.waitForSelector('#nameModal', { state: 'hidden' })
await pageA.waitForFunction(() => document.getElementById('connState').innerText.includes('Synced'), null, { timeout: 15000 })
await pageA.waitForTimeout(600)
assert.equal(await pageA.locator('#pinCount').innerText(), '2')

const ctxB = await browser.newContext({ viewport: { width: 1000, height: 760 }, locale: 'zh-TW' })
const pageB = await ctxB.newPage()
await pageB.goto(`${BASE}/r/${room}`, { waitUntil: 'domcontentloaded' })
await pageB.waitForSelector('#nameModal', { state: 'hidden' })
assert.equal(await pageB.evaluate(() => document.documentElement.lang), 'zh-TW')
await pageB.waitForFunction(() => document.getElementById('connState').innerText.includes('已同步'), null, { timeout: 15000 })
await pageB.waitForFunction(() => document.querySelectorAll('#avatars .avatar').length >= 2, null, { timeout: 15000 })
await pageA.waitForFunction(() => document.querySelectorAll('#avatars .avatar').length >= 2, null, { timeout: 15000 })
await pageB.waitForTimeout(800)
assert.equal(await pageB.locator('#pinCount').innerText(), '2')
await pageB.screenshot({ path: 'tests/e2e/screenshots/61-production-tw.png' })
if (errors.length) console.log('CONSOLE ERRORS', errors)
console.log('PRODUCTION PASSED', { room, base: BASE, errors })
await browser.close()
